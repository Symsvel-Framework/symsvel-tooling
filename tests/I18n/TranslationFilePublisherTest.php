<?php

declare(strict_types=1);

namespace SymSvel\Tooling\Tests\I18n;

use PHPUnit\Framework\TestCase;
use SymSvel\Tooling\I18n\TranslationFilePublisher;

final class TranslationFilePublisherTest extends TestCase
{
    private string $workspace;

    protected function setUp(): void
    {
        $this->workspace = sys_get_temp_dir().'/symsvel-i18n-'.bin2hex(random_bytes(6));
        mkdir($this->workspace.'/backend', 0775, true);
        mkdir($this->workspace.'/bo/src/lib', 0775, true);
    }

    protected function tearDown(): void
    {
        $iterator = new \RecursiveIteratorIterator(
            new \RecursiveDirectoryIterator($this->workspace, \FilesystemIterator::SKIP_DOTS),
            \RecursiveIteratorIterator::CHILD_FIRST,
        );
        foreach ($iterator as $item) {
            $item->isLink() || $item->isFile()
                ? unlink($item->getPathname()) : rmdir($item->getPathname());
        }
        rmdir($this->workspace);
    }

    public function testPublishesReplacesAndSkipsUnchangedGeneratedFile(): void
    {
        $writer = new TranslationFilePublisher();
        $header = "// Generated by SymSvel Languages. Do not edit manually.\n";
        $path = $this->workspace.'/bo/src/lib/i18n/generated/fr.ts';
        $result = $writer->publish($this->workspace.'/backend', 'bo', 'fr',
            $header."export default {\"hello\":\"Bonjour\"} as const;\n");
        self::assertTrue($result['changed']);
        self::assertSame($path, $result['path']);
        self::assertSame(0644, fileperms($path) & 0777);
        self::assertFalse($writer->publish($this->workspace.'/backend', 'bo', 'fr',
            $header."export default {\"hello\":\"Bonjour\"} as const;\n")['changed']);
        self::assertTrue($writer->publish($this->workspace.'/backend', 'bo', 'fr',
            $header."export default {\"hello\":\"Salut\"} as const;\n")['changed']);
        self::assertStringContainsString('Salut', file_get_contents($path));
    }

    public function testRefusesToOverwriteAnUnmanagedFile(): void
    {
        mkdir($this->workspace.'/bo/src/lib/i18n/generated', 0775, true);
        $file = $this->workspace.'/bo/src/lib/i18n/generated/en.ts';
        file_put_contents($file, 'Custom translation');
        try {
            (new TranslationFilePublisher())->publish($this->workspace.'/backend', 'bo', 'en',
                "// Generated by SymSvel Languages. Do not edit manually.\nexport default {} as const;\n");
            self::fail('Unmanaged file must remain untouched.');
        } catch (\RuntimeException) {
            self::assertSame('Custom translation', file_get_contents($file));
        }
    }

    public function testRejectsUninstalledComponentAndSymlinkedOutput(): void
    {
        $writer = new TranslationFilePublisher();
        $content = "// Generated by SymSvel Languages. Do not edit manually.\nexport default {} as const;\n";
        try {
            $writer->publish($this->workspace.'/backend', 'app', 'fr', $content);
            self::fail('Absent component must be rejected.');
        } catch (\RuntimeException) {
        }
        mkdir($this->workspace.'/bo/src/lib/i18n', 0775, true);
        symlink($this->workspace.'/backend', $this->workspace.'/bo/src/lib/i18n/generated');
        $this->expectException(\RuntimeException::class);
        $writer->publish($this->workspace.'/backend', 'bo', 'fr', $content);
    }

    public function testRejectsTraversalAndArbitraryFileContent(): void
    {
        $writer = new TranslationFilePublisher();
        foreach ([
            ['../backend', 'fr', "// Generated by SymSvel Languages. Do not edit manually.\n"],
            ['bo', '../fr', "// Generated by SymSvel Languages. Do not edit manually.\n"],
            ['bo', 'fr', 'Untrusted file'],
        ] as [$scope, $language, $content]) {
            try {
                $writer->publish($this->workspace.'/backend', $scope, $language, $content);
                self::fail('Expected a rejection for invalid input.');
            } catch (\InvalidArgumentException) {
            }
        }
    }
}
