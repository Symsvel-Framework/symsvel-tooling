<?php

declare(strict_types=1);

namespace SymSvel\Tooling\Installation;

use Symfony\Component\Process\Process;

/**
 * Builds the development-only MkDocs site during local project initialization.
 * The production deployment never executes this builder.
 */
final class DevDocumentationBuilder
{
    /** @param null|\Closure(list<string>, string):void $runner */
    public function __construct(private readonly ?\Closure $runner = null)
    {
    }

    public function build(string $workspace): void
    {
        $workspace = realpath($workspace) ?: throw new \RuntimeException('Workspace SymSvel introuvable.');
        $docs = $workspace.'/dev-doc';
        $configuration = $docs.'/mkdocs.yml';
        $requirements = $docs.'/requirements.txt';
        $venv = $docs.'/.venv';
        $site = $docs.'/site';

        if (is_link($docs) || !is_dir($docs) || !is_file($configuration)
            || is_link($configuration) || !is_file($requirements) || is_link($requirements)
            || !is_dir($docs.'/docs') || is_link($docs.'/docs')
            || is_link($venv) || (file_exists($venv) && !is_dir($venv))
            || is_link($site) || (file_exists($site) && !is_dir($site))) {
            throw new \RuntimeException('Arborescence dev-doc invalide ou symbolique.');
        }

        $python = $venv.'/bin/python';
        if (!is_file($python) || !is_executable($python)) {
            $interpreter = getenv('SYMSVEL_SETUP_PYTHON');
            $interpreter = is_string($interpreter) && $interpreter !== ''
                && is_file($interpreter) && is_executable($interpreter) ? $interpreter : 'python3';
            $this->run([$interpreter, '-m', 'venv', $venv], $docs, 180);
        }
        if (is_link($python) && !str_starts_with(realpath($python) ?: '', $venv.'/')) {
            // venv interpreters are frequently symlinks to the system Python.
            // They are valid when generated by Python's venv command.
            if (!is_file($venv.'/pyvenv.cfg')) {
                throw new \RuntimeException('Environnement Python dev-doc non fiable.');
            }
        }
        if (!is_file($python)) {
            throw new \RuntimeException('Environnement Python dev-doc introuvable après initialisation.');
        }

        $this->run([$python, '-m', 'pip', 'install', '--disable-pip-version-check',
            '--no-input', '-r', $requirements], $docs, 600);
        $this->run([$python, '-m', 'mkdocs', 'build', '--clean',
            '--config-file', $configuration, '--site-dir', $site], $docs, 180);

        if (!is_file($site.'/index.html')) {
            throw new \RuntimeException('Build dev-doc incomplet : site/index.html absent.');
        }
    }

    /** @param list<string> $command */
    private function run(array $command, string $cwd, int $timeout): void
    {
        if ($this->runner !== null) {
            ($this->runner)($command, $cwd);
            return;
        }

        $process = new Process($command, $cwd);
        $process->setTimeout($timeout);
        $process->run();
        if (!$process->isSuccessful()) {
            $output = trim($process->getErrorOutput()."\n".$process->getOutput());
            throw new \RuntimeException('Construction MkDocs locale impossible ('
                .implode(' ', array_slice($command, 1, 3)).') : '
                .($output !== '' ? $output : 'aucun diagnostic'));
        }
    }
}
