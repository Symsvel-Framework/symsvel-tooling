<?php

declare(strict_types=1);

namespace SymSvel\Tooling\Module;

/** Reuses immutable compiled migrations during initial installation only. */
final class InitialSetupMigrationResolver
{
    /**
     * @param array{module: string, name: string, path: string, sha256: string} $source
     * @return array{version: string, path: string, entries: array<string, array{sha256: string, doctrine: string}>, created: bool}
     */
    public function resolve(string $backend, array $source, ModuleMigrationCompiler $compiler): array
    {
        if (!preg_match('/^(Version[0-9]{14})\.php$/D', $source['name'], $matches)) {
            throw new \InvalidArgumentException('Version de migration source invalide : '.$source['name']);
        }
        $directory = rtrim($backend, '/').'/migrations';
        if (is_link($directory)) {
            throw new \RuntimeException('Répertoire Doctrine symbolique interdit.');
        }
        $path = $directory.'/'.$source['name'];
        if (file_exists($path) || is_link($path)) {
            if (is_link($path) || !is_file($path) || !is_readable($path)) {
                throw new \RuntimeException('Migration Doctrine existante invalide : '.$source['name']);
            }
            $body = file_get_contents($path);
            $id = $source['module'].'/'.$source['name'];
            if (!is_string($body)
                || !str_contains($body, 'Generated by SymSvel. Never edit a compiled migration.')
                || !str_contains($body, '// '.$id."\n")
                || !str_contains($body, 'final class '.$matches[1].' extends AbstractMigration')) {
                throw new \DomainException('Collision avec une migration Doctrine non reconnue : '.$source['name']);
            }
            $version = 'DoctrineMigrations\\'.$matches[1];
            return [
                'version' => $version,
                'path' => $path,
                'entries' => [$id => ['sha256' => $source['sha256'], 'doctrine' => $version]],
                'created' => false,
            ];
        }
        $migration = $compiler->compile($backend, [$source]);
        if ($migration === null) {
            throw new \RuntimeException('Compilation de migration vide : '.$source['name']);
        }
        return [...$migration, 'created' => true];
    }
}
