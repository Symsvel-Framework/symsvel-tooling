<?php

declare(strict_types=1);

namespace SymSvel\Tooling\Module;

/**
 * Synchronises module-owned Svelte files and generated SvelteKit page routes.
 * Refuses to overwrite or remove any file not recorded with matching content.
 */
final class SvelteModuleSynchronizer
{
    public function __construct(private readonly ComposerModuleSynchronizer $modules = new ComposerModuleSynchronizer())
    {
    }

    /** @return array<string, int> */
    public function sync(string $backend): array
    {
        $backend = realpath($backend) ?: throw new \RuntimeException('Backend introuvable.');
        $workspace = dirname($backend);
        if (is_link($backend.'/.symsvel')) {
            throw new \RuntimeException('Répertoire de registre symbolique interdit.');
        }
        $plan = $this->modules->prepare($backend);
        $targets = [];
        foreach (['bo', 'app', 'front'] as $scope) {
            $app = $workspace.'/'.$scope;
            if (is_link($app)) {
                throw new \RuntimeException('Application Svelte symbolique interdite : '.$scope);
            }
            if (!is_dir($app)) {
                foreach ($plan as $module) {
                    if (isset($module['components'][$scope])) {
                        throw new \RuntimeException('Application Svelte requise mais absente : '.$scope);
                    }
                }
                continue;
            }
            if (is_link($app) || !is_dir($app.'/src/routes') || !is_dir($app.'/src/lib')) {
                throw new \RuntimeException('Application Svelte invalide : '.$scope);
            }
            foreach ($plan as $module) {
                if (!isset($module['components'][$scope])) {
                    continue;
                }
                $slug = $module['module'];
                $source = $module['path'].'/'.$scope.'/src';
                if (!is_dir($source) || is_link($source)) {
                    throw new \RuntimeException('Scope Svelte introuvable : '.$slug.'/'.$scope);
                }
                $files = $this->files($source);
                foreach ($files as $relative => $content) {
                    if (str_starts_with($relative, 'lib/')) {
                        $destination = $app.'/src/lib/vendor/'.$slug.'/'.substr($relative, 4);
                    } elseif (str_starts_with($relative, 'routes/')) {
                        $destination = $app.'/src/lib/vendor/'.$slug.'/'.$relative;
                        if (preg_match('~^routes/(.*)\+page\.svelte$~', $relative, $matches)) {
                            $route = $app.'/src/routes/'.$matches[1].'+page.svelte';
                            $import = '#lib/vendor/'.$slug.'/'.$relative;
                            if (isset($targets[$route])) {
                                throw new \RuntimeException('Collision de routes : '.$route);
                            }
                            $targets[$route] = "<!-- AUTO-GENERATED BY SYMSVEL. DO NOT EDIT. -->\n<script lang=\"ts\">\n  import ModulePage from '".$import."';\n</script>\n\n<ModulePage />\n";
                        }
                    } else {
                        throw new \RuntimeException('Fichier hors lib/routes : '.$relative);
                    }
                    if (isset($targets[$destination]) && $targets[$destination] !== $content) {
                        throw new \RuntimeException('Collision de fichiers : '.$destination);
                    }
                    $targets[$destination] = $content;
                }
            }
        }

        $registry = $backend.'/.symsvel/svelte-files.json';
        if (is_link($registry)) {
            throw new \RuntimeException('Registre symbolique interdit.');
        }
        $previous = is_file($registry) ? json_decode((string) file_get_contents($registry), true, 512, JSON_THROW_ON_ERROR) : [];
        if (!is_array($previous)) {
            throw new \RuntimeException('Registre Svelte invalide.');
        }
        foreach ($previous as $path => $hash) {
            if (!is_string($path) || !is_string($hash) || !preg_match('/^[a-f0-9]{64}$/D', $hash)
                || !$this->managedPath($workspace, $path)) {
                throw new \RuntimeException('Entrée de registre invalide.');
            }
            $parent = dirname($path);
            while ($parent !== $workspace && $parent !== dirname($parent)) {
                if (is_link($parent)) {
                    throw new \RuntimeException('Répertoire symbolique interdit : '.$parent);
                }
                $parent = dirname($parent);
            }
            if (is_link($path) || !is_file($path) || hash_file('sha256', $path) !== $hash) {
                throw new \RuntimeException('Fichier généré modifié ou absent : '.$path);
            }
        }
        foreach ($targets as $path => $content) {
            if (!$this->managedPath($workspace, $path)) {
                throw new \RuntimeException('Destination hors répertoire géré : '.$path);
            }
            if (is_link($path) || (file_exists($path) && (!isset($previous[$path]) || !is_file($path)))) {
                throw new \RuntimeException('Fichier non géré déjà présent : '.$path);
            }
            $parent = dirname($path);
            while ($parent !== $workspace && $parent !== dirname($parent)) {
                if (is_link($parent)) {
                    throw new \RuntimeException('Répertoire symbolique interdit : '.$parent);
                }
                $parent = dirname($parent);
            }
        }
        $changed = 0;
        foreach ($targets as $path => $content) {
            if (!is_file($path) || file_get_contents($path) !== $content) {
                if (!is_dir(dirname($path)) && !mkdir(dirname($path), 0775, true) && !is_dir(dirname($path))) {
                    throw new \RuntimeException('Création de dossier impossible : '.$path);
                }
                if (file_put_contents($path, $content) === false) {
                    throw new \RuntimeException('Écriture impossible : '.$path);
                }
                ++$changed;
            }
        }
        $removed = 0;
        foreach ($previous as $path => $hash) {
            if (!isset($targets[$path])) {
                unlink($path);
                $this->pruneEmptyParents(dirname($path), $workspace);
                ++$removed;
            }
        }
        ksort($targets);
        $next = [];
        foreach ($targets as $path => $content) {
            $next[$path] = hash('sha256', $content);
        }
        if (!is_dir(dirname($registry)) && !mkdir(dirname($registry), 0775, true) && !is_dir(dirname($registry))) {
            throw new \RuntimeException('Registre indisponible.');
        }
        $encoded = json_encode($next, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR)."\n";
        if (!is_file($registry) || file_get_contents($registry) !== $encoded) {
            file_put_contents($registry, $encoded);
        }

        return ['written' => $changed, 'removed' => $removed];
    }

    /** Remove only empty directories below module-managed roots. */
    private function pruneEmptyParents(string $directory, string $workspace): void
    {
        foreach (['bo', 'app', 'front'] as $scope) {
            foreach ([$workspace.'/'.$scope.'/src/lib/vendor', $workspace.'/'.$scope.'/src/routes'] as $root) {
                if (!str_starts_with($directory, $root.'/')) {
                    continue;
                }
                while ($directory !== $root && is_dir($directory) && !is_link($directory)) {
                    if (!@rmdir($directory)) {
                        break;
                    }
                    $directory = dirname($directory);
                }
                return;
            }
        }
    }

    private function managedPath(string $workspace, string $path): bool
    {
        if (str_contains($path, '/./') || str_contains($path, '/../') || str_ends_with($path, '/..')
            || str_ends_with($path, '/.')) {
            return false;
        }
        foreach (['bo', 'app', 'front'] as $scope) {
            $prefix = $workspace.'/'.$scope.'/src/';
            if (str_starts_with($path, $prefix)) {
                $relative = substr($path, strlen($prefix));
                return str_starts_with($relative, 'lib/vendor/') || str_starts_with($relative, 'routes/');
            }
        }
        return false;
    }

    /** @return array<string, string> */
    private function files(string $source): array
    {
        $result = [];
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($source, \FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if ($file->isLink()) {
                throw new \RuntimeException('Lien symbolique interdit : '.$file->getPathname());
            }
            if (!$file->isFile()) {
                continue;
            }
            $relative = substr($file->getPathname(), strlen($source) + 1);
            if (!str_starts_with($relative, 'lib/') && !str_starts_with($relative, 'routes/')) {
                throw new \RuntimeException('Fichier Svelte non pris en charge : '.$relative);
            }
            if (basename($relative) === '.gitkeep') {
                continue;
            }
            $result[$relative] = (string) file_get_contents($file->getPathname());
        }
        ksort($result);
        return $result;
    }
}
