<?php

declare(strict_types=1);

namespace SymSvel\Tooling\Module;

/**
 * Compiles immutable module sources into a Doctrine migration without executing
 * module source files. Adapted from the XCore migration compiler.
 */
final class ModuleMigrationCompiler
{
    /**
     * @param list<array{module: string, name: string, path: string, sha256: string}> $sources
     * @return array{version: string, path: string, entries: array<string, array{sha256: string, doctrine: string}>}|null
     */
    public function compile(string $backend, array $sources): ?array
    {
        if ($sources === []) {
            return null;
        }
        $directory = rtrim($backend, '/').'/migrations';
        if (!is_dir($directory) && !mkdir($directory, 0775, true) && !is_dir($directory)) {
            throw new \RuntimeException('Impossible de créer le répertoire Doctrine.');
        }
        if (is_link($directory)) {
            throw new \RuntimeException('Répertoire Doctrine symbolique interdit.');
        }
        $version = 'Version'.date('YmdHis');
        $suffix = 0;
        while (file_exists($directory.'/'.$version.'.php')) {
            $version = 'Version'.date('YmdHis').sprintf('%02d', ++$suffix);
        }
        $up = [];
        $down = [];
        $entries = [];
        foreach ($sources as $source) {
            $id = $source['module'].'/'.$source['name'];
            $body = file_get_contents($source['path']);
            if ($body === false) {
                throw new \RuntimeException('Lecture de migration impossible : '.$id);
            }
            if (!hash_equals($source['sha256'], hash('sha256', $body))) {
                throw new \RuntimeException('Migration source modifiée pendant la compilation : '.$id);
            }
            $up[] = '        // '.$id."\n".$this->indent($this->extract($body, 'up', $id));
            array_unshift($down, '        // '.$id."\n".$this->indent($this->extract($body, 'down', $id)));
            $entries[$id] = ['sha256' => $source['sha256'], 'doctrine' => 'DoctrineMigrations\\'.$version];
        }
        $upBody = implode("\n", $up);
        $downBody = implode("\n", $down);
        $php = <<<PHP
<?php

declare(strict_types=1);

namespace DoctrineMigrations;

use Doctrine\\DBAL\\Schema\\Schema;
use Doctrine\\Migrations\\AbstractMigration;

/** Generated by SymSvel. Never edit a compiled migration. */
final class {$version} extends AbstractMigration
{
    public function getDescription(): string
    {
        return 'SymSvel compiled module migrations';
    }

    public function up(Schema \$schema): void
    {
{$upBody}
    }

    public function down(Schema \$schema): void
    {
{$downBody}
    }
}
PHP;
        $path = $directory.'/'.$version.'.php';
        if (is_link($path) || file_put_contents($path, $php, LOCK_EX) === false) {
            throw new \RuntimeException('Écriture migration Doctrine impossible : '.$path);
        }
        return ['version' => 'DoctrineMigrations\\'.$version, 'path' => $path, 'entries' => $entries];
    }

    private function extract(string $content, string $method, string $id): string
    {
        $tokens = token_get_all($content);
        $count = count($tokens);
        for ($i = 0; $i < $count; ++$i) {
            $token = $tokens[$i];
            if (!is_array($token) || $token[0] !== T_FUNCTION) {
                continue;
            }
            $j = $i + 1;
            while ($j < $count && is_array($tokens[$j]) && in_array($tokens[$j][0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) {
                ++$j;
            }
            if (!is_array($tokens[$j] ?? null) || $tokens[$j][0] !== T_STRING || $tokens[$j][1] !== $method) {
                continue;
            }
            while ($j < $count && $tokens[$j] !== '{' && $tokens[$j] !== ';') {
                ++$j;
            }
            if (($tokens[$j] ?? null) !== '{') {
                break;
            }
            $depth = 1;
            $body = '';
            for (++$j; $j < $count; ++$j) {
                $part = $tokens[$j];
                if ($part === '{') {
                    ++$depth;
                } elseif ($part === '}' && --$depth === 0) {
                    return trim($body);
                }
                $body .= is_array($part) ? $part[1] : $part;
            }
            break;
        }
        throw new \RuntimeException('Migration '.$id.' sans méthode '.$method.'().');
    }

    private function indent(string $body): string
    {
        if ($body === '') {
            return '        // No operation.';
        }
        $lines = preg_split('/\R/u', $body) ?: [];
        $indent = null;
        foreach ($lines as $line) {
            if (trim($line) === '') {
                continue;
            }
            preg_match('/^[ \t]*/', $line, $matches);
            $length = strlen($matches[0]);
            $indent = $indent === null ? $length : min($indent, $length);
        }
        return implode("\n", array_map(static fn (string $line): string => '        '.substr($line, $indent ?? 0), $lines));
    }
}
