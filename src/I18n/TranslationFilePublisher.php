<?php

declare(strict_types=1);

namespace SymSvel\Tooling\I18n;

/**
 * Publishes a generated dictionary only into an installed local Svelte source.
 * The module renders content; Tooling alone owns workspace file operations.
 */
final class TranslationFilePublisher
{
    private const SIGNATURE = '// Generated by SymSvel Languages. Do not edit manually.';

    /** @return array{path:string,changed:bool} */
    public function publish(string $backend, string $scope, string $language, string $content): array
    {
        if (!in_array($scope, ['bo', 'app', 'front'], true)
            || !preg_match('/^[a-z]{2,4}$/D', $language)) {
            throw new \InvalidArgumentException('Invalid Svelte target or language.');
        }
        if (!str_starts_with($content, self::SIGNATURE."\n")
            || strlen($content) > 2097152) {
            throw new \InvalidArgumentException('Invalid generated translation content.');
        }
        $root = realpath($backend);
        if ($root === false || !is_dir($root) || basename($root) !== 'backend') {
            throw new \RuntimeException('Expected installed backend not found.');
        }
        $workspace = dirname($root);
        $app = $workspace.'/'.$scope;
        if (is_link($app) || !is_dir($app) || !is_dir($app.'/src/lib')
            || realpath($app) !== $app) {
            throw new \RuntimeException('Svelte component is not installed: '.$scope);
        }
        $base = $app.'/src/lib';
        $directory = $base.'/translations/generated';
        foreach ([$base.'/translations', $directory] as $dir) {
            if (is_link($dir) || (file_exists($dir) && !is_dir($dir))) {
                throw new \RuntimeException('Invalid translation output directory.');
            }
            if (!is_dir($dir) && !mkdir($dir, 0775) && !is_dir($dir)) {
                throw new \RuntimeException('Cannot create translation directory.');
            }
        }
        $path = $directory.'/'.$language.'.ts';
        if (is_link($path) || (file_exists($path) && !is_file($path))) {
            throw new \RuntimeException('Invalid translation target.');
        }
        if (is_file($path)) {
            $existing = file_get_contents($path);
            if (!is_string($existing) || !str_starts_with($existing, self::SIGNATURE."\n")) {
                throw new \RuntimeException('Refusing to overwrite an unmanaged translation file.');
            }
            if ($existing === $content) return ['path' => $path, 'changed' => false];
        }
        $temporary = tempnam($directory, '.translations-');
        if ($temporary === false) throw new \RuntimeException('Cannot create translation temporary file.');
        try {
            if (file_put_contents($temporary, $content, LOCK_EX) === false
                || !chmod($temporary, 0644) || !rename($temporary, $path)) {
                throw new \RuntimeException('Cannot atomically publish translation dictionary.');
            }
        } finally {
            if (is_file($temporary)) unlink($temporary);
        }
        return ['path' => $path, 'changed' => true];
    }
}
